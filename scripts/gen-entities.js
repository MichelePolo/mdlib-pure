// Generates src/entities/table.ts from the WHATWG entities.json.
//
//   curl -sSfL https://html.spec.whatwg.org/entities.json -o /tmp/entities.json
//   node scripts/gen-entities.js /tmp/entities.json
//
// Only entities terminated by ";" are kept: CommonMark never decodes the
// legacy semicolon-less forms. Output format: "name:hex[.hex]" joined by ",".
import { readFileSync, writeFileSync } from 'node:fs'

const input = process.argv[2]
if (!input) {
  console.error('usage: node scripts/gen-entities.js <path/to/entities.json>')
  process.exit(1)
}

const json = JSON.parse(readFileSync(input, 'utf8'))
const entries = Object.keys(json)
  .filter((k) => k.startsWith('&') && k.endsWith(';'))
  .map((k) => `${k.slice(1, -1)}:${json[k].codepoints.map((c) => c.toString(16)).join('.')}`)
  .sort()

const out = `// GENERATED by scripts/gen-entities.js — do not edit by hand.
// Source: https://html.spec.whatwg.org/entities.json (${entries.length} entities)
export const TABLE =
  '${entries.join(',')}'
`
writeFileSync(new URL('../src/entities/table.ts', import.meta.url), out)
console.log(`wrote ${entries.length} entities`)
