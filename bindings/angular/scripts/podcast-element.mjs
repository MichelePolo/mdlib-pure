// Before `ng build ngx-mdlib-pure` and `ng test`: bundle the podcast editor
// element (templates/podcast/element.js, shared with the Blazor wrapper) into
// projects/ngx-mdlib-pure/podcast/src/element.generated.ts (gitignored).
//
// - mdlib-pure itself stays an import ('mdlib-pure', 'mdlib-pure/gfm'): the
//   package's peer dependency, not a second copy of the parser.
// - The stylesheets the element adopts in its shadow root (mdlib-pure's
//   theme.css and the sample's podcast.css) are embedded as strings: an
//   Angular library cannot ship CSS that reaches a shadow root otherwise.
// - A .ts file with @ts-nocheck, because ng-packagr compiles TypeScript only.
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { build } from 'esbuild'

const ROOT = new URL('../../../', import.meta.url)
const path = (p) => new URL(p, ROOT).pathname
const OUT = new URL('../projects/ngx-mdlib-pure/podcast/src/element.generated.ts', import.meta.url)

// The podcast sources import the repository's src/ directly: map them to the package.
const packageImports = {
  [path('src/index.ts')]: 'mdlib-pure',
  [path('src/gfm/index.ts')]: 'mdlib-pure/gfm',
}

const result = await build({
  entryPoints: [path('templates/podcast/element.js')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  legalComments: 'none',
  logLevel: 'error',
  plugins: [{
    name: 'mdlib-pure-package',
    setup(b) {
      b.onResolve({ filter: /\/src\/(index|gfm\/index)\.ts$/ }, (args) => {
        const pkg = packageImports[resolve(args.resolveDir, args.path)]
        return pkg ? { path: pkg, external: true } : undefined
      })
    },
  }],
})

const css = (p) => JSON.stringify(readFileSync(path(p), 'utf8'))
// The bundle's own export is untyped (@ts-nocheck): re-export it with a signature.
const exportBlock = /\nexport \{\s*definePodcastEditor\s*\};\s*$/
const code = result.outputFiles[0].text
if (!exportBlock.test(code)) throw new Error('podcast-element: unexpected bundle exports')
writeFileSync(OUT, `// @ts-nocheck
// Generated by bindings/angular/scripts/podcast-element.mjs from templates/podcast/element.js. Do not edit.
${code.replace(exportBlock, '\n')}
/** Define <mdlib-podcast-editor> once; \`styles\`: sheets (or URLs) adopted by its shadow root. */
export const defineElement: (options?: { styles?: ReadonlyArray<CSSStyleSheet | string> }) => void = definePodcastEditor;
/** mdlib-pure's theme.css and the podcast stylesheet, adopted by the element's shadow root. */
export const PODCAST_STYLES: readonly string[] = [${css('styles/theme.css')}, ${css('site/assets/podcast.css')}];
`)
console.log(`wrote ${OUT.pathname.slice(path('').length)}`)
